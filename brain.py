_client = None


def _get_client():
    global _client
    if _client is None:
        import anthropic
        import config

        _client = anthropic.Anthropic(api_key=config.ANTHROPIC_API_KEY)
    return _client


def _model(fast: bool = False) -> str:
    import config

    return config.MODEL_FAST if fast else config.MODEL_MAIN


def _complete(user_prompt: str, *, system: str = PERSONALITY, fast: bool = False,
              max_tokens: int = 600, temperature: float = 1.0) -> str:
    msg = _get_client().messages.create(
        model=_model(fast),
        max_tokens=max_tokens,
        temperature=temperature,
        # Кэшируем системный промпт (−90% на входе при частых вызовах).
        system=[{"type": "text", "text": system, "cache_control": {"type": "ephemeral"}}],
        messages=[{"role": "user", "content": user_prompt}],
    )
    return "".join(b.text for b in msg.content if b.type == "text").strip()


def news_digest(items: list[dict]) -> str:
    """Короткая сводка новостей (3–4 строки) в стиле бота. Работает на Haiku."""
    if not items:
        return ""
    heads = "\n".join(f"- {it['title']}" for it in items[:8])
    prompt = (
        "Свежие футбольные заголовки:\n" + heads + "\n\n"
        "Сделай КОРОТКУЮ сводку в 3–4 строки в своём дерзком стиле по паре самых интересных. "
        "Опирайся ТОЛЬКО на заголовки, деталей не выдумывай. Без длинных списков."
    )
    return _complete(prompt, fast=True, max_tokens=350, temperature=0.7)


def parse_intent(text: str, team_names: list[str]) -> dict:
    """Разобрать вольный вопрос в структуру. Возвращает dict с ключом intent:
    'scenario' (+teams), 'chance' (+player) или 'chat'."""
    import json
    import re

    teams = ", ".join(team_names)
    system = "Ты — парсер запросов. Отвечай ТОЛЬКО валидным JSON, без пояснений и текста вокруг."
    prompt = (
        "Определи намерение сообщения и верни СТРОГО JSON.\n"
        "ГЛАВНЫЕ ПРАВИЛА:\n"
        "1) Если про УЖЕ сыгранный матч (как сыграл, какой был счёт, кто победил в матче "
        "X–Y, в прошедшем времени) — это intent=result.\n"
        "2) Если это ГИПОТЕЗА про будущий исход: одна команда обыгрывает/побеждает/проходит "
        "другую ИЛИ проигрывает/уступает/вылетает от другой — это ВСЕГДА intent=match "
        "(а не scenario), даже если стадия не названа.\n"
        "intent:\n"
        "• \"result\" — вопрос про уже сыгранный матч. Поля team_a, team_b.\n"
        "• \"match\" — гипотеза про будущий исход матча. winner — кто пройдёт дальше, loser — "
        "кто вылетит. «X обыграет Y» → winner=X, loser=Y. «X проиграет Y» → winner=Y, loser=X.\n"
        "• \"botpick\" — просят МНЕНИЕ/ПРОГНОЗ бота ИЛИ сравнение с ним: «твой прогноз на "
        "X–Y», «кого поставишь», «кто победит по-твоему», «сравни мои прогнозы со своими», "
        "«кого бы ты поставил на ближайшие матчи», «твоё мнение о моих ставках». team_a, "
        "team_b — только если назван конкретный матч, иначе не указывай.\n"
        "• \"botbracket\" — просят СЕТКУ бота до чемпиона или его чемпиона турнира: «твоя "
        "сетка», «твой прогноз до чемпиона», «кто по-твоему выиграет турнир», «кого ставишь "
        "в чемпионы». Без полей.\n"
        "• \"news\" — просят новости футбола: «что нового», «новости», «что там в мире "
        "футбола». Без полей.\n"
        "• \"scenario\" — насколько ДАЛЕКО пройдёт команда (до стадии): «дойдёт до финала», "
        "«станет чемпионом». Только когда явно про стадию и без второй команды-соперника.\n"
        "• \"chance\" — про шансы участника (могу ли стать первым, какое место).\n"
        "• \"chat\" — всё остальное.\n"
        f"Известные команды (используй ровно эти написания): {teams}.\n"
        "Стадии scenario: 1/16, 1/8, 1/4, 1/2, финал, чемпион.\n"
        "Примеры (верни ровно такой JSON):\n"
        '«как сыграла Франция - Швеция» -> {"intent":"result","team_a":"Франция","team_b":"Швеция"}\n'
        '«какой счёт был у Бразилии с Японией» -> {"intent":"result","team_a":"Бразилия","team_b":"Япония"}\n'
        '«если Швеция обыграет Францию» -> {"intent":"match","winner":"Швеция","loser":"Франция"}\n'
        '«что будет если Англия проиграет ДР Конго» -> {"intent":"match","winner":"ДР Конго","loser":"Англия"}\n'
        '«твой прогноз на Франция – Швеция» -> {"intent":"botpick","team_a":"Франция","team_b":"Швеция"}\n'
        '«сравни мои прогнозы на ближайшие матчи со своими» -> {"intent":"botpick"}\n'
        '«кого бы ты поставил» -> {"intent":"botpick"}\n'
        '«твоя сетка до чемпиона» -> {"intent":"botbracket"}\n'
        '«кто по-твоему станет чемпионом» -> {"intent":"botbracket"}\n'
        '«что нового в футболе» -> {"intent":"news"}\n'
        '«если Франция станет чемпионом» -> {"intent":"scenario","teams":{"Франция":"чемпион"}}\n'
        '«могу ли я стать первым» -> {"intent":"chance","player":"Кравченко"}\n'
        '«как настроение» -> {"intent":"chat"}\n\n'
        f"Сообщение: «{text}»\nJSON:"
    )
    raw = _complete(prompt, system=system, fast=True, max_tokens=200, temperature=0.0)
    match = re.search(r"\{.*\}", raw, re.S)
    if not match:
        return {"intent": "chat"}
    try:
        data = json.loads(match.group(0))
        return data if isinstance(data, dict) else {"intent": "chat"}
    except (ValueError, TypeError):
        return {"intent": "chat"}


